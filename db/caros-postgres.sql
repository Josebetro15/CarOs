BEGIN;

DROP TABLE IF EXISTS archivos CASCADE;
DROP TABLE IF EXISTS avances CASCADE;
DROP TABLE IF EXISTS preordenes CASCADE;
DROP TABLE IF EXISTS ordenes CASCADE;
DROP TABLE IF EXISTS lecturas CASCADE;
DROP TABLE IF EXISTS senales CASCADE;
DROP TABLE IF EXISTS correos CASCADE;
DROP TABLE IF EXISTS cotizaciones CASCADE;
DROP TABLE IF EXISTS refacciones CASCADE;
DROP TABLE IF EXISTS proveedores CASCADE;
DROP TABLE IF EXISTS vehiculos CASCADE;
DROP TABLE IF EXISTS solicitudes_cuenta CASCADE;
DROP TABLE IF EXISTS recuperaciones CASCADE;
DROP TABLE IF EXISTS clientes CASCADE;
DROP TABLE IF EXISTS mecanicos CASCADE;
DROP TABLE IF EXISTS encargados CASCADE;
DROP TABLE IF EXISTS usuarios CASCADE;

CREATE TABLE IF NOT EXISTS usuarios (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  correo varchar(255) NOT NULL UNIQUE,
  contrasena varchar(255) NOT NULL,
  nombre varchar(255) NOT NULL,
  rol varchar(20) NOT NULL CHECK (rol IN ('CLIENTE', 'MECANICO', 'ENCARGADO'))
);

CREATE TABLE IF NOT EXISTS clientes (
  usuario_id bigint PRIMARY KEY REFERENCES usuarios (id)
);

CREATE TABLE IF NOT EXISTS mecanicos (
  usuario_id bigint PRIMARY KEY REFERENCES usuarios (id)
);

CREATE TABLE IF NOT EXISTS encargados (
  usuario_id bigint PRIMARY KEY REFERENCES usuarios (id)
);

CREATE TABLE IF NOT EXISTS vehiculos (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  placa varchar(255) NOT NULL UNIQUE,
  marca varchar(255) NOT NULL,
  modelo varchar(255) NOT NULL,
  anio integer NOT NULL,
  km integer NOT NULL DEFAULT 0,
  vin varchar(255) NOT NULL UNIQUE,
  salud integer NOT NULL DEFAULT 100,
  inventario_inicial varchar(2000),
  cliente_id bigint REFERENCES clientes (usuario_id)
);

CREATE TABLE IF NOT EXISTS senales (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  vehiculo_id bigint NOT NULL REFERENCES vehiculos (id),
  codigo varchar(255) NOT NULL,
  descripcion varchar(255) NOT NULL,
  gravedad varchar(255) NOT NULL,
  sugerencia varchar(255) NOT NULL,
  estado varchar(255) NOT NULL DEFAULT 'open',
  creado_en timestamptz DEFAULT now(),
  cerrado_en timestamptz
);

CREATE TABLE IF NOT EXISTS lecturas (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  vehiculo_id bigint NOT NULL REFERENCES vehiculos (id),
  vin varchar(255) NOT NULL,
  km integer NOT NULL,
  origen varchar(255) NOT NULL,
  codigos_dtc varchar(255) NOT NULL DEFAULT '',
  unidad_nueva boolean NOT NULL DEFAULT false,
  creado_en timestamptz DEFAULT now(),
  mecanico_id bigint REFERENCES mecanicos (usuario_id),
  encargado_id bigint REFERENCES encargados (usuario_id),
  CONSTRAINT lecturas_autor CHECK (num_nonnulls(mecanico_id, encargado_id) <= 1)
);

CREATE TABLE IF NOT EXISTS ordenes (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  folio varchar(255) NOT NULL UNIQUE,
  vehiculo_id bigint NOT NULL REFERENCES vehiculos (id),
  descripcion varchar(255) NOT NULL,
  tecnico varchar(255) NOT NULL,
  programada_en timestamptz DEFAULT now(),
  horas numeric(10,2) NOT NULL DEFAULT 1.0,
  estado varchar(255) NOT NULL DEFAULT 'pending',
  nombre_refaccion varchar(255),
  nombre_proveedor varchar(255),
  dias_entrega integer,
  mecanico_id bigint REFERENCES mecanicos (usuario_id),
  encargado_id bigint REFERENCES encargados (usuario_id)
);

CREATE TABLE IF NOT EXISTS preordenes (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  vehiculo_id bigint NOT NULL REFERENCES vehiculos (id),
  codigo varchar(255) NOT NULL,
  sku varchar(255) NOT NULL,
  nombre_refaccion varchar(255) NOT NULL,
  nombre_proveedor varchar(255) NOT NULL,
  precio numeric(12,2) NOT NULL,
  dias_entrega integer NOT NULL,
  llegada timestamptz NOT NULL,
  folio varchar(255) NOT NULL,
  de_almacen boolean NOT NULL DEFAULT false,
  creado_en timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS avances (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  vehiculo_id bigint NOT NULL REFERENCES vehiculos (id),
  mecanico_id bigint REFERENCES mecanicos (usuario_id),
  encargado_id bigint REFERENCES encargados (usuario_id),
  tipo varchar(255) NOT NULL,
  mensaje varchar(2000) NOT NULL,
  creado_en timestamptz DEFAULT now(),
  CONSTRAINT avances_autor CHECK (num_nonnulls(mecanico_id, encargado_id) <= 1)
);

CREATE TABLE IF NOT EXISTS archivos (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  avance_id bigint NOT NULL REFERENCES avances (id),
  tipo_archivo varchar(255) NOT NULL,
  url varchar(255) NOT NULL
);

CREATE TABLE IF NOT EXISTS refacciones (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sku varchar(255) NOT NULL UNIQUE,
  nombre varchar(255) NOT NULL,
  categoria varchar(255) NOT NULL,
  precio numeric(12,2) NOT NULL,
  existencia integer NOT NULL DEFAULT 0,
  compatibilidad varchar(255) NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS proveedores (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre varchar(255) NOT NULL UNIQUE,
  ciudad varchar(255) NOT NULL
);

CREATE TABLE IF NOT EXISTS cotizaciones (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  refaccion_id bigint NOT NULL REFERENCES refacciones (id),
  proveedor_id bigint NOT NULL REFERENCES proveedores (id),
  precio numeric(12,2) NOT NULL,
  dias_entrega integer NOT NULL
);

CREATE TABLE IF NOT EXISTS correos (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  clave varchar(255) NOT NULL UNIQUE,
  correo_destino varchar(255) NOT NULL,
  nombre_destino varchar(255) NOT NULL,
  asunto varchar(255) NOT NULL,
  cuerpo varchar(2000) NOT NULL,
  tipo varchar(255) NOT NULL,
  placa varchar(255),
  creado_en timestamptz DEFAULT now(),
  cliente_id bigint REFERENCES clientes (usuario_id),
  mecanico_id bigint REFERENCES mecanicos (usuario_id),
  encargado_id bigint REFERENCES encargados (usuario_id),
  CONSTRAINT correos_remitente CHECK (num_nonnulls(mecanico_id, encargado_id) <= 1)
);

CREATE TABLE IF NOT EXISTS recuperaciones (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id bigint NOT NULL REFERENCES usuarios (id),
  token varchar(255) NOT NULL UNIQUE,
  creado_en timestamptz NOT NULL DEFAULT now(),
  expira_en timestamptz NOT NULL
);

CREATE TABLE IF NOT EXISTS solicitudes_cuenta (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  correo varchar(255) NOT NULL UNIQUE,
  nombre varchar(255) NOT NULL,
  contrasena varchar(255) NOT NULL,
  rol varchar(20) NOT NULL CHECK (rol IN ('CLIENTE', 'MECANICO', 'ENCARGADO')),
  codigo_correo varchar(6) NOT NULL,
  token_correo varchar(255) NOT NULL UNIQUE,
  codigo_acceso varchar(6),
  correo_ok boolean NOT NULL DEFAULT false,
  intentos integer DEFAULT 0,
  reenvios integer DEFAULT 0,
  creado_en timestamptz NOT NULL DEFAULT now(),
  expira_en timestamptz NOT NULL
);

